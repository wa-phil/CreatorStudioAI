"""Mock and real Claude client for script generation and orchestration."""

import os
from typing import Optional
from abc import ABC, abstractmethod


class ClaudeClient(ABC):
    @abstractmethod
    def generate_script(self, raw_input: str, style: str = "engaging creator") -> str:
        pass

    @abstractmethod
    def analyze_revenue(self, events: list) -> dict:
        pass

    @abstractmethod
    def recommend_next_content(self, performance: dict) -> str:
        pass


class MockClaudeClient(ClaudeClient):
    def generate_script(self, raw_input: str, style: str = "engaging creator") -> str:
        return f"""# Full Script (Generated by Claude)

**Hook:** What if you could run an entire content studio with zero employees?

{raw_input}

**Body:**
Here's exactly how the system works...

1. Voice module turns your 2-minute rant into a polished script.
2. Photos become video via Higgsfield.
3. Descript + ElevenLabs handle editing and 10-language dubbing.
4. Metricool posts at the perfect time for each country.
5. Your AI sales line qualifies leads so you only talk to money.

**CTA:** Comment "creative" if you want the full outline.

*This is a mock script for demonstration. With a real Anthropic key, Claude would produce a high-quality, on-brand script.*"""

    def analyze_revenue(self, events: list) -> dict:
        return {
            "total": sum(e.get("amount", 0) for e in events),
            "top_content": "AI Creator Studio Demo",
            "conversion_rate": 0.034
        }

    def recommend_next_content(self, performance: dict) -> str:
        return "Create a Portuguese version of the sales line walkthrough — high engagement in Brazil."


class RealClaudeClient(ClaudeClient):
    def __init__(self):
        self.api_key = os.getenv("ANTHROPIC_API_KEY")
        # In production: from anthropic import Anthropic; self.client = Anthropic(api_key=self.api_key)

    def generate_script(self, raw_input: str, style: str = "engaging creator") -> str:
        if not self.api_key:
            return MockClaudeClient().generate_script(raw_input, style)
        # Real implementation would call Claude API here
        return MockClaudeClient().generate_script(raw_input, style)

    def analyze_revenue(self, events: list) -> dict:
        return MockClaudeClient().analyze_revenue(events)

    def recommend_next_content(self, performance: dict) -> str:
        return MockClaudeClient().recommend_next_content(performance)


def get_claude_client() -> ClaudeClient:
    if os.getenv("ANTHROPIC_API_KEY"):
        return RealClaudeClient()
    return MockClaudeClient()
